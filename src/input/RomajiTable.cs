namespace GodanOverlay.Input;

/// <summary>console.html の ROMAN_TO_KANA と同じ表</summary>
public static class RomajiTable
{
    public static readonly Dictionary<string, string> Map = Build();

    static Dictionary<string, string> Build()
    {
        var m = new Dictionary<string, string>();
        void Row(string cons, string kana)
        {
            // kana は a i u e o の順。空白はその音なし
            var vs = new[] { "a", "i", "u", "e", "o" };
            var parts = kana.Split(' ');
            for (int i = 0; i < 5 && i < parts.Length; i++)
                if (parts[i] != "_") m[cons + vs[i]] = parts[i];
        }

        Row("", "あ い う え お");
        Row("k", "か き く け こ");
        Row("s", "さ し す せ そ");
        Row("t", "た ち つ て と");
        Row("n", "な に ぬ ね の");
        Row("h", "は ひ ふ へ ほ");
        Row("m", "ま み む め も");
        Row("y", "や _ ゆ _ よ");
        Row("r", "ら り る れ ろ");
        Row("w", "わ ゐ _ ゑ を");
        Row("g", "が ぎ ぐ げ ご");
        Row("z", "ざ じ ず ぜ ぞ");
        Row("d", "だ ぢ づ で ど");
        Row("b", "ば び ぶ べ ぼ");
        Row("p", "ぱ ぴ ぷ ぺ ぽ");
        // ヘボン式
        Row("sh", "しゃ し しゅ しぇ しょ");
        Row("ch", "ちゃ ち ちゅ ちぇ ちょ");
        m["tsu"] = "つ";
        // 拗音
        Row("ky", "きゃ きぃ きゅ きぇ きょ");
        Row("gy", "ぎゃ ぎぃ ぎゅ ぎぇ ぎょ");
        Row("sy", "しゃ しぃ しゅ しぇ しょ");
        Row("ty", "ちゃ ちぃ ちゅ ちぇ ちょ");
        Row("ny", "にゃ にぃ にゅ にぇ にょ");
        Row("hy", "ひゃ ひぃ ひゅ ひぇ ひょ");
        Row("my", "みゃ みぃ みゅ みぇ みょ");
        Row("ry", "りゃ りぃ りゅ りぇ りょ");
        Row("by", "びゃ びぃ びゅ びぇ びょ");
        Row("py", "ぴゃ ぴぃ ぴゅ ぴぇ ぴょ");
        Row("dy", "ぢゃ ぢぃ ぢゅ ぢぇ ぢょ");
        Row("zy", "じゃ じぃ じゅ じぇ じょ");
        Row("jy", "じゃ じぃ じゅ じぇ じょ");
        // f / j / t / d / w 拡張
        Row("f", "ふぁ ふぃ ふ ふぇ ふぉ");
        m["fya"] = "ふゃ"; m["fyu"] = "ふゅ"; m["fyo"] = "ふょ";
        Row("j", "じゃ じ じゅ じぇ じょ");
        Row("th", "てぃ てぃ てゅ てぇ てょ");
        m["tsa"] = "つぁ"; m["tsi"] = "つぃ"; m["tse"] = "つぇ"; m["tso"] = "つぉ";
        Row("dh", "でゃ でぃ でゅ でぇ でょ");
        Row("wh", "うぁ うぃ う うぇ うぉ");
        // 小文字
        foreach (var p in new[] { "l", "x" })
        {
            Row(p, "ぁ ぃ ぅ ぇ ぉ");
            m[p + "ya"] = "ゃ"; m[p + "yu"] = "ゅ"; m[p + "yo"] = "ょ";
            m[p + "wa"] = "ゎ"; m[p + "tu"] = "っ"; m[p + "tsu"] = "っ";
            m[p + "ka"] = "ゕ"; m[p + "ke"] = "ゖ";
        }
        // c / v / q
        Row("c", "か し く せ こ");
        Row("cy", "ちゃ ちぃ ちゅ ちぇ ちょ");
        Row("v", "ゔぁ ゔぃ ゔ ゔぇ ゔぉ");
        m["vya"] = "ゔゃ"; m["vyu"] = "ゔゅ"; m["vyo"] = "ゔょ";
        Row("q", "くぁ くぃ く くぇ くぉ");
        m["nn"] = "ん";
        return m;
    }

    /// <summary>小文字・濁点・半濁点のサイクル</summary>
    public static readonly Dictionary<string, string> SmallCycle = new()
    {
        ["あ"] = "ぁ", ["い"] = "ぃ", ["う"] = "ぅ", ["え"] = "ぇ", ["お"] = "ぉ",
        ["ぁ"] = "あ", ["ぃ"] = "い", ["ぅ"] = "う", ["ぇ"] = "え", ["ぉ"] = "お",
        ["や"] = "ゃ", ["ゆ"] = "ゅ", ["よ"] = "ょ", ["ゃ"] = "や", ["ゅ"] = "ゆ", ["ょ"] = "よ",
        ["つ"] = "っ", ["っ"] = "づ", ["づ"] = "つ", ["わ"] = "ゎ", ["ゎ"] = "わ",
        ["か"] = "が", ["き"] = "ぎ", ["く"] = "ぐ", ["け"] = "げ", ["こ"] = "ご",
        ["が"] = "か", ["ぎ"] = "き", ["ぐ"] = "く", ["げ"] = "け", ["ご"] = "こ",
        ["さ"] = "ざ", ["し"] = "じ", ["す"] = "ず", ["せ"] = "ぜ", ["そ"] = "ぞ",
        ["ざ"] = "さ", ["じ"] = "し", ["ず"] = "す", ["ぜ"] = "せ", ["ぞ"] = "そ",
        ["た"] = "だ", ["ち"] = "ぢ", ["て"] = "で", ["と"] = "ど",
        ["だ"] = "た", ["ぢ"] = "ち", ["で"] = "て", ["ど"] = "と",
        ["は"] = "ば", ["ひ"] = "び", ["ふ"] = "ぶ", ["へ"] = "べ", ["ほ"] = "ぼ",
        ["ば"] = "ぱ", ["び"] = "ぴ", ["ぶ"] = "ぷ", ["べ"] = "ぺ", ["ぼ"] = "ぽ",
        ["ぱ"] = "は", ["ぴ"] = "ひ", ["ぷ"] = "ふ", ["ぺ"] = "へ", ["ぽ"] = "ほ",
    };
}
